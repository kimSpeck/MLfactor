defineLambda <- function(nGroups, nItems, miItems, miWeight, nOutcome) {
  ###
  # define lambda matrix 
  ## input:
  # nGroups   - [scalar] number of groups with different factor loading patterns to join in block matrix manner
  # nItems    - [scalar] number of items (equal across groups); each group gets this number of items
  # miItems   - [vector] number of items with measurement invariance violations in each group
  # miWeight  - [list] factor loadings for the non-MI items; groups in list, weights in vector within list 
  # nOutcome  - [scalar] number of outcome variables; !needs to be multiplied by group
  ## output:
  # lambda     - [matrix] factor loading matrix with factors in columns and items in rows [factors x items]
  ###
  
  # # test it
  # miWeight <- list(c(0), c(0, 0.8)) 
  # miItems <- c(1, 2)
  # nItems <- 9
  # nGroups <- 3
  
  # check if arguments are supplied correctly
  if (nGroups > 1) {
    # check that enough information for miItems is supplied for each group
    if (!all(nGroups-1 == length(miItems) && nGroups-1 == length(miWeight))) {
      stop("You did not provide enough information on miItems for all groups!")
    }
  }
  
  # check that miWeight is a list
  if (nGroups > 1 & miItems > 0) {
    if (!is.list(miWeight)) {
      stop("miWeight has to be a list with groups as list elements and weights as vectors within")
      
      # check that number of miItems matches number of weights
    } else if (!all(miItems == sapply(seq_len(length(miWeight)), function(i) length(miWeight[[i]])))) {
      stop("number of supplied weights does not match number of MI violating items.")
    }
  }
  
  
  # factor loading matrix for basic group (without MI violations)
  lambda <- cbind(TS = rep(params$dgp$trueScoreLoad, nItems),
                  specificEffects = diag(nItems) * params$dgp$specificLoad)
  
  # multiple group case: factor loading matrices for MI violation group(s)
  if (nGroups > 1) {
    lambdaMI <- sapply(seq_len(nGroups - 1), function(iGroup) {
      if (miItems > 0) {
        cbind(TS = c(rep(params$dgp$trueScoreLoad, nItems-miItems[iGroup]), miWeight[[iGroup]]),
              specificEffects = diag(nItems) * params$dgp$specificLoad)  
      } else {
        cbind(TS = rep(params$dgp$trueScoreLoad, nItems),
              specificEffects = diag(nItems) * params$dgp$specificLoad)
      }
      
    }, simplify = F)
    
    # concatenate factor loading matrices in block matrix style
    lambda <- adiag(lambda, do.call(adiag, lambdaMI))
  }
  
  # add outcome variables (separately for groups to be able to introduce correlations)
  lambda <- adiag(lambda, diag(params$dgp$nOutcome*nGroups))
  
  # name rows and columns 
  colnames(lambda) <- c(paste0(rep(c("T", 
                                     sapply(seq(nItems), 
                                            function(iItem) {paste0("S", iItem)})), times = nGroups), 
                               "_g", rep(seq_len(nGroups), each = params$dgp$trueScore + nItems)), 
                        paste0("Y", seq_len(params$dgp$nOutcome), "_g", 
                               rep(seq_len(nGroups), each = params$dgp$nOutcome)))
  
  rownames(lambda) <- c(paste0(rep(c(sapply(seq(nItems), 
                                            function(iItem) {paste0("X", iItem)})), times = nGroups), 
                               "_g", rep(seq_len(nGroups), each = nItems)), 
                        paste0("Y", seq_len(params$dgp$nOutcome), "_g", 
                               rep(seq_len(nGroups), each = params$dgp$nOutcome)))
  
  lambda
} 

