definePhi <- function(nFactors, sigmaT, sigmaS, nItems, scalarMI = F, miItems = 0, varNames = NULL) {
  ###
  # define factor correlation matrix
  ## input:
  # nFactors  - [scalar] number of factors to generate matrix
  # sigmaT    - [scalar] variance of the true score composite
  # sigmaS    - [scalar] variance of the specific item effects (usually identical for all items)
  # nItems    - [scalar] number of items and hence, specific item effect factors
  # scalarMI  - [boolean] if scalar measurement invariance violation is present variance 
  #                       of the specific item effect is generated by mean differences 
  #                       between group instead of random variation in specific item effect
  # miItems   - [scalar] number of items with scalar measurement invariance violation
  ## output:
  # phi       - [matrix] factor correlation matrix with factors in rows and columns [factor x factor]
  ###
  if (!scalarMI) {
    phi <- diag(nFactors) * c(rep(c(sigmaT, rep(sigmaS, nItems)), times = params$dgp$nGroups),  
                              rep(params$sigmaErrY, params$dgp$nOutcome * params$dgp$nGroups))
  } else {
    phi <- diag(nFactors) * c(
      rep(rep(c(sigmaT, sigmaS, 0), c(1, nItems-miItems, miItems)), times = params$dgp$nGroups),  
      rep(params$sigmaErrY, params$dgp$nOutcome * params$dgp$nGroups)) # residual variance!
  }
  
  if (!is.null(varNames)){
    colnames(phi) <- rownames(phi) <- varNames
  }
  
  phi
}

defineBeta <- function(nFactors, betaT, betaS, nItems, varNames) {
  ###
  # define matrix of path coefficients
  ## input:
  # nFactors  - [scalar] number of factors to generate empty path coefficient matrix
  # betaT     - [vector] coefficient of the true score composite on the outcome (in this case scalar)
  # betaS     - [vector] coefficients of the specific item factors on the outcome 
  # nItems    - [scalar] number of items, i.e., specific item factors
  # varNames  - [vector] vector of factor names to set values in matrix (readable and easy)
  ## output:
  # betaMat   - [matrix] matrix of path coefficients with factors in rows and columns
  ###
  if (params$dgp$nGroups != 2) {
    stop("This function is only tested for two groups!")
  }
  
  # beta matrix without any effect
  betaMat <- matrix(rep(0, nFactors + nFactors*(nFactors-1)), ncol = nFactors, byrow = T)
  colnames(betaMat) <- rownames(betaMat) <- varNames
  
  # outcome variables are sorted in the following order: Y1_g1 Y2_g1 Y2_g2 Y2_g2
  outVars <- varNames[grep("^Y", varNames)]
  for (iOut in seq_along(outVars)) {
    if (grepl("g1", outVars[iOut])) { # this is group 1
      betaMat[outVars[iOut],] <- c(betaT, betaS, 
                                   rep(0, nItems + params$dgp$trueScore), 
                                   rep(0, params$dgp$nOutcome*params$dgp$nGroups))
    } else { # this is group 2
      # T & S 
      betaMat[outVars[iOut],] <-c(rep(0, nItems + params$dgp$trueScore), 
                                  betaT, betaS, 
                                  rep(0, params$dgp$nOutcome*params$dgp$nGroups))
    }
  }
  
  betaMat
}

# calculate the error variance of the item with MI violation
getErrorVar <- function(loadingVec, varianceVec, targetVar) {
  ###
  # calculate the error variance for items in which loadings on the true score changes
  ## input:
  # loadingVec  - [vector] vector of factor loadings on all factors that affect the item
  # varianceVec - [vector] vector of factor variances of all factors that affect the item
  # targetVar   - [scalar] target variance of the item 
  ## output:
  #             - [scalar] amount of error variance to arrive at target variance of the item
  ###
  
  targetVar - sum(loadingVec**2 * varianceVec)
}

